def validate_answers(answers: dict) -> dict:
    """
    Валидирует ответы пользователя.
    answers — словарь {ключ_вопроса: ответ или список ответов}
    Возвращает провалидированный словарь.
    """
    validated = {}
    for key, config in QUESTIONS.items():
        if key not in answers:
            raise ValueError(f"Отсутствует ответ на вопрос: {config['question']}")

        answer = answers[key]

        if config["type"] == "single":
            if answer not in config["options"]:
                raise ValueError(f"Недопустимый ответ '{answer}' на вопрос '{key}'")
            validated[key] = answer

        elif config["type"] == "multiple":
            if not isinstance(answer, list) or len(answer) == 0:
                raise ValueError(f"Вопрос '{key}' требует список ответов (минимум 1)")
            for a in answer:
                if a not in config["options"]:
                    raise ValueError(f"Недопустимый ответ '{a}' на вопрос '{key}'")
            validated[key] = answer

    return validated


